package main

import (
	"fmt"
	"log"
	"os"
	"regexp"
	"strings"

	"github.com/nakamasato/kubernetes-training/doc"
	yaml "gopkg.in/yaml.v3"
)

func main() {

	f, err := os.Open("readme.yml")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	d := yaml.NewDecoder(f)

	var m map[string][]Version

	if err := d.Decode(&m); err != nil {
		log.Fatal(err)
	}

	versions, err := resolveVersions(m["versions"])
	if err != nil {
		log.Fatal(err)
	}
	generateReadme(versions, "README.md")

	updateVersionInReadme(versions, "contents/README.md")
}

type Version struct {
	Name       string         `yaml:"name"`
	Version    string         `yaml:"version"`
	RepoUrl    string         `yaml:"repoUrl"`
	Category   string         `yaml:"category"`
	ToDo       bool           `yaml:"todo"`
	Dir        string         `yaml:"dir"`
	Source     *VersionSource `yaml:"source,omitempty"`
	TagPrefix  string         `yaml:"tagPrefix,omitempty"`
	ReleaseURL string         `yaml:"releaseUrl,omitempty"`
}

type VersionSource struct {
	Path    string `yaml:"path"`
	Pattern string `yaml:"pattern"`
}

// Resolve every source before writing either README. Repeated identical matches
// are fine (install/uninstall instructions); conflicting pins are an error.
func resolveVersions(versions []Version) ([]Version, error) {
	resolved := append([]Version(nil), versions...)
	seen := make(map[string]bool)
	for i := range resolved {
		v := &resolved[i]
		if seen[v.Name] {
			return nil, fmt.Errorf("duplicate version entry %q", v.Name)
		}
		seen[v.Name] = true
		if v.Source == nil {
			continue
		}
		if v.Version != "" {
			return nil, fmt.Errorf("%s: use either version or source", v.Name)
		}
		data, err := os.ReadFile(v.Source.Path)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", v.Name, err)
		}
		pattern, err := regexp.Compile(v.Source.Pattern)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", v.Name, err)
		}
		if pattern.NumSubexp() != 1 {
			return nil, fmt.Errorf("%s: source pattern must have exactly one capture group", v.Name)
		}
		matches := pattern.FindAllStringSubmatch(string(data), -1)
		if len(matches) == 0 {
			return nil, fmt.Errorf("%s: no version found in %s", v.Name, v.Source.Path)
		}
		for _, match := range matches {
			if match[1] == "" {
				return nil, fmt.Errorf("%s: empty version in %s", v.Name, v.Source.Path)
			}
			if v.Version != "" && v.Version != match[1] {
				return nil, fmt.Errorf("%s: conflicting versions in %s", v.Name, v.Source.Path)
			}
			v.Version = match[1]
		}
	}
	return resolved, nil
}

func (v Version) getReleaseUrl() string {
	if v.ReleaseURL != "" {
		return v.ReleaseURL
	}
	if v.Version == "" {
		return v.RepoUrl
	} else if v.Version == "latest" {
		return v.RepoUrl + "/releases"
	} else {
		return v.RepoUrl + "/releases/tag/" + v.TagPrefix + v.Version
	}
}

func (v Version) getToDoString() string {
	if v.ToDo {
		return "(ToDo)"
	} else {
		return ""
	}
}

func generateReadme(versions []Version, filename string) {
	book := doc.NewMarkDown()
	book.WriteTitle("Kubernetes Training", doc.LevelTitle).
		WriteLines(2)

	book.WriteList(fmt.Sprintf("Read on Website: %s", book.GetLink("https://www.nakamasato.com/kubernetes-training", "https://www.nakamasato.com/kubernetes-training")))
	book.WriteList(
		fmt.Sprintf(
			"Read on GitHub: %s (All files were moved to `contents` in %s)",
			book.GetLink("contents", "contents"),
			book.GetLink("#105", "https://github.com/nakamasato/kubernetes-training/pull/105"),
		),
	)
	book.WriteList("Version indexes are generated by `go run readme.go` from the pinned sample sources in `readme.yml`.")
	book.WriteList("Run `pre-commit install` once; the hook updates both READMEs on commit. Stage any generated changes and commit again.")
	book.WriteLines(1)

	book.WriteTitle("Versions", doc.LevelSection)
	book.WriteLines(1)
	book.WriteWordLine("Versions reflect repository examples and CI tools, not necessarily the latest upstream releases. Unpinned projects link to their repositories.")
	book.WriteLines(1)
	for _, version := range versions {

		book.WriteList(
			fmt.Sprintf(
				"%s: %s%s",
				version.Name,
				version.link(),
				version.getToDoString(),
			),
		)
	}

	book.WriteLines(1)
	book.WriteTitle("Cloud Native Trail Map", doc.LevelSection)
	book.WriteLines(1)
	book.WriteList(book.GetLink("https://github.com/cncf/trailmap", "https://github.com/cncf/trailmap"))
	book.WriteList(book.GetLink("https://www.cncf.io/blog/2018/03/08/introducing-the-cloud-native-landscape-2-0-interactive-edition/", "https://www.cncf.io/blog/2018/03/08/introducing-the-cloud-native-landscape-2-0-interactive-edition/"))

	book.WriteWordLine(fmt.Sprintf("!%s", book.GetLink("", "https://github.com/cncf/trailmap/blob/master/CNCF_TrailMap_latest.png?raw=true")))

	err := book.Export(filename)
	if err != nil {
		log.Fatal(err)
	}
}

func (v Version) link() string {
	label := v.Version
	if label == "" {
		label = "not pinned"
	}
	return fmt.Sprintf("[%s](%s)", label, v.getReleaseUrl())
}

func versionSection(versions []Version) string {
	var section strings.Builder
	section.WriteString("# Versions\n\n<!-- Generated by go run readme.go; edit the sources in readme.yml. -->\n\n")
	for _, v := range versions {
		fmt.Fprintf(&section, "1. %s: %s%s\n", v.Name, v.link(), v.getToDoString())
	}
	return section.String()
}

func replaceVersionSection(input string, versions []Version) (string, error) {
	start := strings.Index(input, "# Versions\n")
	end := strings.Index(input, "# Contents\n")
	if start < 0 || end < start {
		return "", fmt.Errorf("missing Versions/Contents section boundaries")
	}
	return input[:start] + versionSection(versions) + "\n" + input[end:], nil
}

func updateVersionInReadme(versions []Version, filename string) {
	input, err := os.ReadFile(filename)
	if err != nil {
		log.Fatal(err)
	}
	output, err := replaceVersionSection(string(input), versions)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filename, []byte(output), 0644); err != nil {
		log.Fatal(err)
	}
}
